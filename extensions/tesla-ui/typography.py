"""Build Montserrat glyph atlases for the native canvas (no global font changes)."""
import json
from pathlib import Path
from PIL import Image,ImageDraw,ImageFont
from generate import ROOT,screen
CHARS=''.join(chr(c) for c in range(32,127))+'°−—·'

def generate():
    styles=[];labels=[]
    for key,node in sorted(screen().items()):
        if not isinstance(node,dict) or 'fontSize' not in node:continue
        style=(node['fontSize'],node['colorTab']['color0'])
        if style not in styles:styles.append(style)
        p=node['position']
        labels.append((node['id'],styles.index(style),p['width'],p['height'],int(node['alignment']==37),node.get('text','')))
    gear_dim=len(styles);styles.append((21,0x383a3e))
    out=ROOT/'assets/type';out.mkdir(exist_ok=True)
    header=['/* Generated by typography.py. */','struct glyph {int code,x,y,w,h,advance;};',
            'struct type_label {int id,style,width,height,center;const char *initial;};']
    for i,(size,color) in enumerate(styles):
        font=ImageFont.truetype(str(ROOT/'design/Montserrat.ttf'),size);font.set_variation_by_axes([400])
        cell=size+12;height=size*2;columns=12
        repertoire=CHARS if size<48 else '?—P'
        columns=min(columns,len(repertoire))
        atlas=Image.new('RGBA',(cell*columns,height*((len(repertoire)+columns-1)//columns)))
        draw=ImageDraw.Draw(atlas);rows=[]
        for n,ch in enumerate(CHARS):
            slot=repertoire.find(ch)
            if slot<0:slot=0
            x=(slot%columns)*cell;y=(slot//columns)*height
            if ch in repertoire:draw.text((x+3,y+height/2),ch,font=font,anchor='lm',fill=f'#{color:06x}')
            rows.append('{%d,%d,%d,%d,%d,%d}'%(ord(ch),x,y,cell,height,round(font.getlength(ch))))
        atlas.save(out/f'{i}.png')
        header.append('static const struct glyph glyphs_%d[]={%s};'%(i,','.join(rows)))
    header.append('static const struct glyph *glyph_styles[]={'+','.join('glyphs_'+str(i) for i in range(len(styles)))+'};')
    header.append('static const struct type_label type_labels[]={'+','.join('{'+','.join(map(str,row[:-1]))+','+json.dumps(row[-1],ensure_ascii=False)+'}' for row in labels)+'};')
    header.append('#define GEAR_DIM_STYLE %d'%gear_dim)
    header.append('#define TYPE_STYLES %d\n#define TYPE_LABELS %d\n#define TYPE_GLYPHS %d'%(len(styles),len(labels),len(CHARS)))
    (ROOT/'typography_data.h').write_text('\n'.join(header)+'\n')

if __name__=='__main__':generate()
