"""Crop Blender frames without rescaling; retain their positions in a fixed canvas."""
import argparse
from pathlib import Path
from PIL import Image
from generate import ROOT

def pack(source):
    names=[f'camera-{i:02}' for i in range(65)]
    names += [f'{v}-{m:02x}' for v in ('park','drive') for m in range(64)]
    names += [f'{v}-hinge-{m:02x}-{f:02}' for v in ('park','drive') for m in (1,2,4,8,16,32,63) for f in range(1,12)]
    out=ROOT/'assets/motion';out.mkdir(exist_ok=True);rows=[];total=0
    for name in names:
        im=Image.open(source/(name+'.png')).convert('RGBA')
        if name.startswith(('park-','drive-')) and '-hinge-' not in name:
            im.save(ROOT/'assets/body'/(name+'.png'))
            if name.endswith('-00'):im.save(ROOT/'assets'/(name.split('-')[0]+'.png'))
        box=im.getchannel('A').getbbox()
        assert box and box[0]>0 and box[1]>0 and box[2]<600 and box[3]<360,(name,box)
        im=im.crop(box);im.save(out/(name+'.png'))
        x,y=box[:2];w,h=im.size
        rows.append('{"%s.png",%d,%d,%d,%d}'%(name,x,y,w,h))
        if name.startswith('camera'):total+=w*h*4
    (ROOT/'motion_data.h').write_text('/* Generated by pack_motion.py. Coordinates in a 600 x 360 canvas. */\n'
        'struct vehicle_sprite {const char *name;int x,y,w,h;};\nstatic const struct vehicle_sprite vehicle_sprites[]={\n'+',\n'.join(rows)+'\n};\n')
    print('Camera decoded pixel budget:',total,'bytes')
if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('source',type=Path);a=p.parse_args();pack(a.source)
